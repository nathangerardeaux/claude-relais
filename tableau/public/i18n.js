export const TEXTES = { fr, en };

// Placeholders that analyse.mjs writes into the index (data, kept in French there) -> key of their text.
export const DEBUT = '(début)';
export const MARQUES = { [DEBUT]: 'marque.debut', '(sans titre)': 'marque.sansTitre', '[résumé /compact]': 'marque.compact', "[notification d'une tâche de fond]": 'marque.notification' };

let langue = 'en';
export const langueActive = () => langue;
export function definirLangue(l) { langue = l === 'fr' ? 'fr' : 'en'; return langue; }
// Locale for numbers and dates.
export const locale = () => (langue === 'fr' ? 'fr-FR' : 'en-US');

export function t(cle, p = {}) {
  const v = TEXTES[langue][cle] ?? TEXTES.en[cle] ?? cle;
  return v.replace(/\{(\w+)(?:\|([^|}]*)\|([^}]*))?\}/g, (m, x, un, plusieurs) => {
    if (!(x in p)) return m;
    if (un === undefined) return String(p[x]);
    const n = Math.abs(Number(p[x]));
    return (langue === 'fr' ? n < 2 : n === 1) ? un : plusieurs; // French: 0 and 1 are singular
  });
}
